def is_junk_word(w):
    """判断一个词是否是无意义的垃圾词，不应作为敏感词"""
    # 1. 所有单字词全部移除 (504个)
    #    单字词误报率极高: 如 "把", "b", "p", "B", "&" 等
    if len(w) == 1:
        return True

    # 2. 白名单匹配
    if w in WHITELIST:
        return True

    return False


def main():
    # 读取当前词库
    with open(WORD_FILE, "r", encoding="utf-8") as f:
        words = [line.strip() for line in f if line.strip()]

    original_count = len(words)

    # 过滤: 白名单 + 单字词
    removed = []
    kept = []
    for w in words:
        if is_junk_word(w):
            removed.append(w)
        else:
            kept.append(w)

    # 去重 (保持顺序)
    seen = set()
    deduped = []
    dup_count = 0
    for w in kept:
        if w in seen:
            dup_count += 1
        else:
            seen.add(w)
            deduped.append(w)

    # 写回
    with open(WORD_FILE, "w", encoding="utf-8", newline="\n") as f:
        for w in deduped:
            f.write(w + "\n")

    # 报告
    print("=" * 60)
    print("敏感词库清洗报告")
    print("=" * 60)
    print(f"  清洗前词数:   {original_count:>10,}")
    print(f"  白名单移除:   {len(removed):>10,}")
    print(f"  去重移除:     {dup_count:>10,}")
    print(f"  清洗后词数:   {len(deduped):>10,}")
    print(f"  净减少:       {original_count - len(deduped):>10,}")
    print()

    if removed:
        print("移除的词:")
        for w in sorted(removed):
            print(f"  - {w}")

    # 验证
    with open(WORD_FILE, "rb") as f:
        raw = f.read()
    has_bom = raw[:3] == b'\xef\xbb\xbf'
    has_crlf = b'\r\n' in raw
    print()
    print(f"编码: {'UTF-8 有BOM' if has_bom else 'UTF-8 无BOM'}")
    print(f"换行符: {'CRLF' if has_crlf else 'LF (Unix)'}")


if __name__ == "__main__":
    main()
