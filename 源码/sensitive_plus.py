class SensitivePlusEngine:
    """
    敏感词检测Plus引擎

    基于ToolGood.Words方案A + jieba词边界校验:
    1. 文本归一化 (全角→半角 + 繁体→简体 + 去除干扰符号)
    2. AC自动机匹配归一化文本
    3. jieba词边界校验 (防止子串误报, 如 "性器" 匹配 "技术性器件")
    4. 返回原始文本中的位置 (通过映射表)

    相比原引擎的优势: 支持全角/繁体/符号干扰变体检测
    相比纯AC匹配的优势: jieba边界校验防止子串误报
    """

    # 2字中文敏感词, jieba可能拆分但确实需要检测 (跳过边界校验)
    _ALLOW_INNER = {"脑残", "傻逼", "煞笔", "傻B", "傻b", "傻X", "傻x"}

    # 永远不接受的词 (总是误报的子串)
    _BLOCKLIST_INNER = {"中出", "女干", "性病"}

    def __init__(self, words):
        """
        初始化引擎
        :param words: 敏感词列表
        """
        self._lock = threading.Lock()
        self._jieba_lock = threading.Lock()
        self._words = list(words)
        self._word_set = set(words)
        self._max_word_len = max((len(w) for w in words), default=1)

        # 构建AC自动机
        self._automaton = ahocorasick.Automaton()
        for w in self._words:
            self._automaton.add_word(w, w)
        self._automaton.make_automaton()

        # 将3+字中文敏感词加入jieba词典, 提升分词准确性
        added = 0
        for w in self._words:
            if self._has_cjk(w) and not self._is_pure_ascii_alnum(w) and len(w) >= 3:
                try:
                    jieba.add_word(w, freq=2000000)
                    added += 1
                except Exception:
                    pass

        print(f"敏感词检测Plus引擎初始化完成: {len(self._words)} 个敏感词, jieba词典扩展{added}词")

    @staticmethod
    def _is_pure_ascii_alnum(w):
        return w.isascii() and w.isalnum()

    @staticmethod
    def _has_cjk(w):
        return any('\u4e00' <= ch <= '\u9fff' for ch in w)

    @staticmethod
    def _has_ascii_alnum(w):
        return any(ch.isascii() and ch.isalnum() for ch in w)

    @classmethod
    def _is_mixed_cjk_ascii(cls, w):
        return cls._has_cjk(w) and cls._has_ascii_alnum(w)

    @staticmethod
    def _is_ascii_alnum(ch):
        return ch.isascii() and ch.isalnum()

    def _normalize(self, text):
        """
        文本归一化:
        1. 全角→半角 (NFKC)
        2. 繁体→简体
        3. 去除干扰符号 (同时保留位置映射)
        
        :return: (归一化后的文本, 位置映射表)
                 位置映射表: normalized_pos -> original_pos
        """
        # Step 1: NFKC 归一化 (全角→半角, 兼容性字符分解)
        # 注意: NFKC 会改变字符数 (如 ｓｂ → sb), 需要建立映射
        normalized = []
        orig_pos_map = []  # normalized_pos -> original_pos
        
        for i, ch in enumerate(text):
            # NFKC 归一化
            nfkced = unicodedata.normalize('NFKC', ch)
            
            # 繁体→简体
            if nfkced in _T2S_MAP:
                nfkced = _T2S_MAP[nfkced]
            
            # 如果归一化后是干扰符号, 跳过 (不加入归一化文本)
            if nfkced in _SKIP_CHARS or _SKIP_PATTERN.match(nfkced):
                continue
            
            # NFKC 可能将一个字符展开为多个 (如 ㌀ → 5%, 但很少见)
            for j, nc in enumerate(nfkced):
                normalized.append(nc)
                orig_pos_map.append(i)
        
        normalized_text = ''.join(normalized)
        return normalized_text, orig_pos_map

    def _check_boundary(self, normalized, norm_start, norm_end, word,
                        token_start_set, token_end_set, token_span_set):
        """
        词边界校验: 判断匹配是否跨越jieba分词边界 (防止子串误报)

        :return: True=有效匹配, False=子串误报
        """
        # 黑名单: 永远拒绝 (总是误报的子串)
        if word in self._BLOCKLIST_INNER:
            return False

        # 1. 纯ASCII字母数字: 检查左右邻接字符 (如 sb 不应匹配出 assimilation 中的子串)
        if self._is_pure_ascii_alnum(word):
            left = normalized[norm_start - 1] if norm_start > 0 else ''
            right = normalized[norm_end] if norm_end < len(normalized) else ''
            return (not left or not self._is_ascii_alnum(left)) and \
                   (not right or not self._is_ascii_alnum(right))

        # 2. 中英混合词 (傻B, 傻x): jieba会拆分, 直接接受
        if self._is_mixed_cjk_ascii(word):
            return True

        # 3. 纯中文词: 使用jieba边界校验
        # 3a. ALLOW_INNER: 手动确认的2字敏感词, jieba可能拆分但确实敏感
        if word in self._ALLOW_INNER:
            return True

        # 3b. 精确token匹配: 匹配恰好是一个完整分词
        if (norm_start, norm_end) in token_span_set:
            return True

        # 3c. 跨完整token: 起点是某token起点, 终点是某token终点
        if norm_start in token_start_set and norm_end in token_end_set:
            return True

        # 3d. 其他情况: 子串误报 (如 "性器" 跨越 "性"+"器件" 边界)
        return False

    def scan(self, text):
        """
        扫描文本, 返回敏感词匹配结果

        :param text: 原始文本
        :return: list of (original_start, original_end_exclusive, keyword)
        """
        if not text:
            return []

        # Step 1: 文本归一化
        normalized, orig_pos_map = self._normalize(text)

        if not normalized:
            return []

        # Step 2: AC自动机匹配归一化后的文本
        raw_matches = []
        seen = set()  # 去重: (start, end, word)

        for end_idx, word in self._automaton.iter(normalized):
            start_idx = end_idx - len(word) + 1
            key = (start_idx, end_idx + 1, word)
            if key in seen:
                continue
            seen.add(key)
            # 白名单过滤: 跳过常见词
            if word in _WHITELIST:
                continue
            raw_matches.append((start_idx, end_idx + 1, word))

        if not raw_matches:
            return []

        # Step 3: jieba词边界校验 (防止子串误报)
        with self._jieba_lock:
            tokens = list(jieba.tokenize(normalized))

        token_start_set = set()
        token_end_set = set()
        token_span_set = set()
        for tok, s, e in tokens:
            token_start_set.add(s)
            token_end_set.add(e)
            token_span_set.add((s, e))

        valid_matches = []
        for norm_start, norm_end, word in raw_matches:
            if self._check_boundary(normalized, norm_start, norm_end, word,
                                    token_start_set, token_end_set, token_span_set):
                valid_matches.append((norm_start, norm_end, word))

        # Step 4: 将归一化文本中的位置映射回原始文本
        results = []
        for norm_start, norm_end, word in valid_matches:
            orig_start = orig_pos_map[norm_start]
            orig_end_idx = norm_end - 1
            if orig_end_idx >= len(orig_pos_map):
                orig_end_idx = len(orig_pos_map) - 1
            orig_end = orig_pos_map[orig_end_idx] + 1  # exclusive

            results.append((orig_start, orig_end, word))

        # 按位置排序
        results.sort(key=lambda x: x[0])
        return results

    def find_words(self, text):
        """
        扫描文本, 返回去重后的敏感词列表
        :param text: 原始文本
        :return: sorted list of unique words
        """
        matches = self.scan(text)
        return sorted({w for _, _, w in matches})

    def highlight(self, text):
        """
        高亮敏感词 (用 ** 包裹)
        :param text: 原始文本
        :return: 高亮后的文本
        """
        matches = self.scan(text)
        if not matches:
            return text
        
        # 去除重叠 (保留最长的)
        spans = sorted(matches, key=lambda x: (x[0], -(x[1] - x[0])))
        out = []
        cur = 0
        for s, e, _w in spans:
            if s < cur:
                continue
            out.append(text[cur:s])
            out.append("**")
            out.append(text[s:e])
            out.append("**")
            cur = e
        out.append(text[cur:])
        return ''.join(out)
