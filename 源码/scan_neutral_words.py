short_chinese = [w for w in words if len(w) <= 2 and re.match(r'^[\u4e00-\u9fa5]+$', w)]
print(f'\n=== 2字以内纯中文词共 {len(short_chinese)} 个 (前30个示例) ===')
for w in sorted(short_chinese)[:30]:
    print(f'  {w}')

